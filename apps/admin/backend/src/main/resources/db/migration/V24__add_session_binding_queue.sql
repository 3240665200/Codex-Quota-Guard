-- All queue transitions lock the corresponding official_accounts row. These rows,
-- leases and unique current-device/session columns also fence separate instances.
create table session_binding_accounts (
    official_account_id uuid primary key references official_accounts(id) on delete cascade,
    active_attempt_id uuid,
    quarantined boolean not null default false,
    reason varchar(100),
    recovery_id uuid,
    recovery_started_at timestamp with time zone,
    updated_at timestamp with time zone not null
);

create table session_binding_attempts (
    id uuid primary key,
    sequence_id bigint generated by default as identity unique,
    user_id uuid not null references users(id) on delete cascade,
    device_id uuid not null,
    enrollment_id uuid not null references meter_devices(id),
    team_id uuid not null references teams(id),
    team_version bigint not null,
    official_account_id uuid not null references official_accounts(id) on delete cascade,
    connection_revision uuid not null,
    status varchar(32) not null,
    created_at timestamp with time zone not null,
    expires_at timestamp with time zone not null,
    operation_id uuid,
    operation_started_at timestamp with time zone,
    before_session_ids text,
    official_account_key varchar(160),
    official_user_key varchar(320),
    candidate_session_id varchar(512),
    candidate_display_name varchar(1000),
    candidate_platform varchar(320),
    candidate_fetched_at timestamp with time zone,
    error_code varchar(100),
    constraint session_binding_attempt_status check (status in
        ('QUEUED','PREPARING','READY_FOR_LOGIN','DETECTING','AWAITING_CONFIRMATION','BOUND','CANCELLED','EXPIRED','REJECTED'))
);
create index session_binding_queue_idx on session_binding_attempts(official_account_id,status,sequence_id);
create index session_binding_attempt_device_idx on session_binding_attempts(user_id,device_id,sequence_id);

create table session_bindings (
    id uuid primary key,
    attempt_id uuid not null unique references session_binding_attempts(id),
    user_id uuid not null references users(id) on delete cascade,
    device_id uuid not null,
    enrollment_id uuid not null references meter_devices(id),
    team_id uuid not null references teams(id),
    team_version bigint not null,
    official_account_id uuid not null references official_accounts(id) on delete cascade,
    connection_revision uuid not null,
    session_id varchar(512) not null,
    active_device_id uuid unique,
    active_session_id varchar(512),
    status varchar(24) not null,
    match_method varchar(40) not null,
    verification_level varchar(40) not null,
    created_at timestamp with time zone not null,
    ended_at timestamp with time zone,
    constraint session_binding_active_session unique(official_account_id,active_session_id),
    constraint session_binding_status check (status in ('ACTIVE','ENDED','INVALIDATED')),
    constraint session_binding_active_columns check
      ((status='ACTIVE' and active_device_id is not null and active_session_id is not null
          and active_device_id=device_id and active_session_id=session_id and ended_at is null)
       or (status<>'ACTIVE' and active_device_id is null and active_session_id is null and ended_at is not null))
);
create index session_binding_user_device_idx on session_bindings(user_id,device_id,created_at);
