import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const frontend=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(frontend,'../../..');
const manifest=fs.readFileSync(path.join(repo,'apps/client/meter/Cargo.toml'),'utf8');
const version=manifest.match(/^version = "([^"]+)"/m)?.[1];
if(!version||!/^\d+\.\d+\.\d+$/.test(version))throw Error('Meter release requires a three-part numeric version.');
const source=path.join(process.env.CARGO_TARGET_DIR||'D:/BuildCache/pingche/cache/rust','release/quota-guard-meter.exe');
const output=path.resolve(process.argv[2]||`D:/BuildCache/pingche/artifacts/meter/${version}`);
const key=process.env.METER_SIGNING_PRIVATE_KEY_PATH||'D:/BuildCache/pingche/private/meter-updater/meter-update.key';
const pinned=fs.readFileSync(path.join(repo,'apps/client/meter/resources/update-public.key'),'utf8').trim();
if(fs.readFileSync(key+'.pub','utf8').trim()!==pinned)throw Error('Meter signing key does not match the pinned publisher.');
fs.mkdirSync(output,{recursive:true});
const installer=`quota-guard-meter_${version}_windows-x86_64.exe`;const target=path.join(output,installer);
fs.copyFileSync(source,target);
const bytes=fs.readFileSync(target);const pe=bytes.readUInt32LE(0x3c);
if(bytes.readUInt16LE(pe+4)!==0x8664)throw Error('This packaging entry point expects Windows x64.');
const env={...process.env};delete env.TAURI_SIGNING_PRIVATE_KEY;delete env.TAURI_SIGNING_PRIVATE_KEY_PATH;delete env.TAURI_SIGNING_PRIVATE_KEY_PASSWORD;
const args=[path.join(frontend,'node_modules/@tauri-apps/cli/tauri.js'),'signer','sign','-f',key,'--app-version',version];
if(process.env.METER_SIGNING_PRIVATE_KEY_PASSWORD)env.TAURI_SIGNING_PRIVATE_KEY_PASSWORD=process.env.METER_SIGNING_PRIVATE_KEY_PASSWORD;
else args.push('-p','');
args.push(target);
const sign=spawnSync(process.execPath,args,{cwd:frontend,env,stdio:'ignore',windowsHide:true,timeout:30000});
if(sign.status!==0)throw Error('Meter signing failed.');
const signature=fs.readFileSync(target+'.sig','utf8').trim();
if(!Buffer.from(signature,'base64').toString('utf8').includes(`\tversion:${version}`))throw Error('Meter signature is not version-bound.');
const sourceCommit=spawnSync('git',['rev-parse','HEAD'],{cwd:repo,encoding:'utf8',windowsHide:true}).stdout.trim();
const metadata={component:'METER',version,target:'windows',arch:'x86_64',installer,signature:installer+'.sig',sha256:crypto.createHash('sha256').update(bytes).digest('hex'),bytes:bytes.length,sourceCommit};
fs.writeFileSync(path.join(output,'package-manifest.json'),JSON.stringify(metadata,null,2)+'\n');
fs.writeFileSync(path.join(output,'SHA256SUMS.txt'),`${metadata.sha256}  ${installer}\n${crypto.createHash('sha256').update(fs.readFileSync(target+'.sig')).digest('hex')}  ${installer}.sig\n`);
console.log(JSON.stringify({...metadata,directory:output}));
